-- CLÍNICA VETERINARIA
--   * Las PK y FK relacionadas conservan exactamente el mismo tipo de dato


BEGIN;

DROP SCHEMA IF EXISTS clinica_veterinaria CASCADE;
CREATE SCHEMA clinica_veterinaria;
SET search_path TO clinica_veterinaria, public;


-- 1. TABLAS PRINCIPALES


CREATE TABLE dueno (
    cedula_dueno  BIGINT       NOT NULL,
    nombres       VARCHAR(80)  NOT NULL,
    apellidos     VARCHAR(80)  NOT NULL,
    direccion     VARCHAR(180) NOT NULL,

    CONSTRAINT pk_dueno
        PRIMARY KEY (cedula_dueno),

    CONSTRAINT ck_dueno_cedula_positiva
        CHECK (cedula_dueno > 0),

    CONSTRAINT ck_dueno_nombres_no_vacios
        CHECK (BTRIM(nombres) <> ''),

    CONSTRAINT ck_dueno_apellidos_no_vacios
        CHECK (BTRIM(apellidos) <> ''),

    CONSTRAINT ck_dueno_direccion_no_vacia
        CHECK (BTRIM(direccion) <> '')
);


CREATE TABLE dueno_telefono (
    cedula_dueno  BIGINT      NOT NULL,
    telefono      VARCHAR(25) NOT NULL,

    CONSTRAINT pk_dueno_telefono
        PRIMARY KEY (cedula_dueno, telefono),

    CONSTRAINT fk_dueno_telefono_dueno
        FOREIGN KEY (cedula_dueno)
        REFERENCES dueno (cedula_dueno)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT ck_dueno_telefono_formato
        CHECK (telefono ~ '^[0-9+() -]{7,25}$')
);


CREATE TABLE veterinario (
    cedula_veterinario   BIGINT       NOT NULL,
    nombre_completo      VARCHAR(160) NOT NULL,
    tarjeta_profesional  BIGINT       NOT NULL,
    especialidad         VARCHAR(100) NOT NULL,

    CONSTRAINT pk_veterinario
        PRIMARY KEY (cedula_veterinario),

    CONSTRAINT uq_veterinario_tarjeta_profesional
        UNIQUE (tarjeta_profesional),

    CONSTRAINT ck_veterinario_cedula_positiva
        CHECK (cedula_veterinario > 0),

    CONSTRAINT ck_veterinario_tarjeta_positiva
        CHECK (tarjeta_profesional > 0),

    CONSTRAINT ck_veterinario_nombre_no_vacio
        CHECK (BTRIM(nombre_completo) <> ''),

    CONSTRAINT ck_veterinario_especialidad_no_vacia
        CHECK (BTRIM(especialidad) <> '')
);


CREATE TABLE mascota (
    id_mascota        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cedula_dueno      BIGINT      NOT NULL,
    nombre            VARCHAR(80) NOT NULL,
    especie           VARCHAR(50) NOT NULL,
    raza              VARCHAR(80),
    sexo              CHAR(1)     NOT NULL,
    fecha_nacimiento  DATE        NOT NULL,
    microchip         BIGINT,

    CONSTRAINT pk_mascota
        PRIMARY KEY (id_mascota),

    CONSTRAINT fk_mascota_dueno
        FOREIGN KEY (cedula_dueno)
        REFERENCES dueno (cedula_dueno)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_mascota_microchip
        UNIQUE (microchip),

    CONSTRAINT ck_mascota_nombre_no_vacio
        CHECK (BTRIM(nombre) <> ''),

    CONSTRAINT ck_mascota_especie_no_vacia
        CHECK (BTRIM(especie) <> ''),

    CONSTRAINT ck_mascota_raza_no_vacia
        CHECK (raza IS NULL OR BTRIM(raza) <> ''),

    CONSTRAINT ck_mascota_sexo
        CHECK (sexo IN ('M', 'F', 'O')),

    CONSTRAINT ck_mascota_fecha_nacimiento
        CHECK (fecha_nacimiento <= CURRENT_DATE),

    CONSTRAINT ck_mascota_microchip_positivo
        CHECK (microchip IS NULL OR microchip > 0)
);


CREATE TABLE cita (
    id_cita               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_mascota            BIGINT       NOT NULL,
    cedula_veterinario    BIGINT       NOT NULL,
    fecha                 DATE         NOT NULL,
    hora                  TIME(0)      NOT NULL,
    motivo                VARCHAR(250) NOT NULL,
    estado                VARCHAR(20)  NOT NULL DEFAULT 'PROGRAMADA',

    CONSTRAINT pk_cita
        PRIMARY KEY (id_cita),

    CONSTRAINT fk_cita_mascota
        FOREIGN KEY (id_mascota)
        REFERENCES mascota (id_mascota)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_cita_veterinario
        FOREIGN KEY (cedula_veterinario)
        REFERENCES veterinario (cedula_veterinario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_cita_veterinario_fecha_hora
        UNIQUE (cedula_veterinario, fecha, hora),

    CONSTRAINT uq_cita_mascota_fecha_hora
        UNIQUE (id_mascota, fecha, hora),

    CONSTRAINT ck_cita_motivo_no_vacio
        CHECK (BTRIM(motivo) <> ''),

    CONSTRAINT ck_cita_estado
        CHECK (
            estado IN (
                'PROGRAMADA',
                'CONFIRMADA',
                'ATENDIDA',
                'CANCELADA',
                'NO_ASISTIO'
            )
        )
);


CREATE TABLE diagnostico (
    id_diagnostico  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cita         BIGINT NOT NULL,
    descripcion     TEXT   NOT NULL,
    observaciones   TEXT,

    CONSTRAINT pk_diagnostico
        PRIMARY KEY (id_diagnostico),

    CONSTRAINT fk_diagnostico_cita
        FOREIGN KEY (id_cita)
        REFERENCES cita (id_cita)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    -- Garantiza que una cita tenga como máximo un diagnóstico.
    CONSTRAINT uq_diagnostico_id_cita
        UNIQUE (id_cita),

    CONSTRAINT ck_diagnostico_descripcion_no_vacia
        CHECK (BTRIM(descripcion) <> '')
);


CREATE TABLE medicamento (
    id_medicamento      SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre_generico     VARCHAR(120) NOT NULL,
    presentacion        VARCHAR(120) NOT NULL,
    concentracion       VARCHAR(80)  NOT NULL,
    forma_farmaceutica  VARCHAR(80)  NOT NULL,

    CONSTRAINT pk_medicamento
        PRIMARY KEY (id_medicamento),

    CONSTRAINT uq_medicamento_descripcion
        UNIQUE (
            nombre_generico,
            presentacion,
            concentracion,
            forma_farmaceutica
        ),

    CONSTRAINT ck_medicamento_id_positivo
        CHECK (id_medicamento > 0),

    CONSTRAINT ck_medicamento_nombre_no_vacio
        CHECK (BTRIM(nombre_generico) <> ''),

    CONSTRAINT ck_medicamento_presentacion_no_vacia
        CHECK (BTRIM(presentacion) <> ''),

    CONSTRAINT ck_medicamento_concentracion_no_vacia
        CHECK (BTRIM(concentracion) <> ''),

    CONSTRAINT ck_medicamento_forma_no_vacia
        CHECK (BTRIM(forma_farmaceutica) <> '')
);


-- Entidad débil:
-- PK completa = (id_diagnostico, numero_prescripcion).
CREATE TABLE prescripcion (
    id_diagnostico       BIGINT   NOT NULL,
    numero_prescripcion  SMALLINT NOT NULL,
    id_medicamento       SMALLINT NOT NULL,
    fecha_emision        DATE     NOT NULL DEFAULT CURRENT_DATE,
    dosis                NUMERIC(10,2) NOT NULL,
    unidad               VARCHAR(30)   NOT NULL,
    frecuencia           VARCHAR(80)   NOT NULL,
    via_administracion   VARCHAR(60)   NOT NULL,
    duracion_dias        SMALLINT,
    indicaciones         TEXT,

    CONSTRAINT pk_prescripcion
        PRIMARY KEY (id_diagnostico, numero_prescripcion),

    CONSTRAINT fk_prescripcion_diagnostico
        FOREIGN KEY (id_diagnostico)
        REFERENCES diagnostico (id_diagnostico)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_prescripcion_medicamento
        FOREIGN KEY (id_medicamento)
        REFERENCES medicamento (id_medicamento)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_prescripcion_numero
        CHECK (numero_prescripcion > 0),

    CONSTRAINT ck_prescripcion_dosis
        CHECK (dosis > 0),

    CONSTRAINT ck_prescripcion_unidad_no_vacia
        CHECK (BTRIM(unidad) <> ''),

    CONSTRAINT ck_prescripcion_frecuencia_no_vacia
        CHECK (BTRIM(frecuencia) <> ''),

    CONSTRAINT ck_prescripcion_via_no_vacia
        CHECK (BTRIM(via_administracion) <> ''),

    CONSTRAINT ck_prescripcion_duracion
        CHECK (duracion_dias IS NULL OR duracion_dias > 0)
);


CREATE TABLE vacuna (
    id_vacuna         SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(120) NOT NULL,
    fabricante        VARCHAR(120) NOT NULL,
    lote              VARCHAR(80)  NOT NULL,
    fecha_vencimiento DATE         NOT NULL,

    CONSTRAINT pk_vacuna
        PRIMARY KEY (id_vacuna),

    CONSTRAINT uq_vacuna_lote
        UNIQUE (nombre, fabricante, lote),

    CONSTRAINT ck_vacuna_id_positivo
        CHECK (id_vacuna > 0),

    CONSTRAINT ck_vacuna_nombre_no_vacio
        CHECK (BTRIM(nombre) <> ''),

    CONSTRAINT ck_vacuna_fabricante_no_vacio
        CHECK (BTRIM(fabricante) <> ''),

    CONSTRAINT ck_vacuna_lote_no_vacio
        CHECK (BTRIM(lote) <> '')
);


-- Entidad débil:
-- PK completa = (id_mascota, numero_registro).
CREATE TABLE registro_vacunacion (
    id_mascota       BIGINT   NOT NULL,
    numero_registro  SMALLINT NOT NULL,
    id_vacuna        SMALLINT NOT NULL,
    fecha_aplicacion DATE     NOT NULL,
    proxima_dosis    DATE,

    CONSTRAINT pk_registro_vacunacion
        PRIMARY KEY (id_mascota, numero_registro),

    CONSTRAINT fk_registro_vacunacion_mascota
        FOREIGN KEY (id_mascota)
        REFERENCES mascota (id_mascota)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_registro_vacunacion_vacuna
        FOREIGN KEY (id_vacuna)
        REFERENCES vacuna (id_vacuna)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_registro_vacunacion_evento
        UNIQUE (id_mascota, id_vacuna, fecha_aplicacion),

    CONSTRAINT ck_registro_vacunacion_numero
        CHECK (numero_registro > 0),

    CONSTRAINT ck_registro_vacunacion_fecha
        CHECK (fecha_aplicacion <= CURRENT_DATE),

    CONSTRAINT ck_registro_vacunacion_proxima_dosis
        CHECK (
            proxima_dosis IS NULL
            OR proxima_dosis >= fecha_aplicacion
        )
);



-- 2. ÍNDICES SOBRE CLAVES FORÁNEAS


CREATE INDEX ix_mascota_cedula_dueno
    ON mascota (cedula_dueno);

CREATE INDEX ix_cita_id_mascota
    ON cita (id_mascota);

CREATE INDEX ix_cita_cedula_veterinario
    ON cita (cedula_veterinario);

CREATE INDEX ix_prescripcion_id_medicamento
    ON prescripcion (id_medicamento);

CREATE INDEX ix_registro_vacunacion_id_vacuna
    ON registro_vacunacion (id_vacuna);



-- 3. REGLAS DE NEGOCIO ENTRE TABLAS


-- 3.1. Impide registrar una vacuna aplicada después de su vencimiento.
CREATE OR REPLACE FUNCTION fn_validar_vacuna_vigente()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_fecha_vencimiento DATE;
BEGIN
    SELECT fecha_vencimiento
      INTO v_fecha_vencimiento
      FROM vacuna
     WHERE id_vacuna = NEW.id_vacuna;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'No existe la vacuna con id_vacuna = %',
            NEW.id_vacuna;
    END IF;

    IF NEW.fecha_aplicacion > v_fecha_vencimiento THEN
        RAISE EXCEPTION
            'La vacuna % venció el % y no puede aplicarse el %',
            NEW.id_vacuna,
            v_fecha_vencimiento,
            NEW.fecha_aplicacion;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_validar_vacuna_vigente
BEFORE INSERT OR UPDATE OF id_vacuna, fecha_aplicacion
ON registro_vacunacion
FOR EACH ROW
EXECUTE FUNCTION fn_validar_vacuna_vigente();


-- 3.2. Impide que una prescripción tenga fecha anterior a la cita.
CREATE OR REPLACE FUNCTION fn_validar_fecha_prescripcion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_fecha_cita DATE;
BEGIN
    SELECT c.fecha
      INTO v_fecha_cita
      FROM diagnostico d
      JOIN cita c
        ON c.id_cita = d.id_cita
     WHERE d.id_diagnostico = NEW.id_diagnostico;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'No fue posible determinar la cita del diagnóstico %',
            NEW.id_diagnostico;
    END IF;

    IF NEW.fecha_emision < v_fecha_cita THEN
        RAISE EXCEPTION
            'La prescripción no puede emitirse antes de la cita (%).',
            v_fecha_cita;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_validar_fecha_prescripcion
BEFORE INSERT OR UPDATE OF id_diagnostico, fecha_emision
ON prescripcion
FOR EACH ROW
EXECUTE FUNCTION fn_validar_fecha_prescripcion();

COMMIT;
